// Colles à venir
// ---------------------------------------------------------------------------

function renderCollesSection(state, onChange) {
  const section = document.createElement('div');
  section.className = 'section';
  section.innerHTML = '<h2>Colles à venir</h2>';

  const todayIso = todayISO(new Date());
  const colles = state.oneOffEvents
    .filter((e) => e.category === 'colle' && e.date >= todayIso)
    .sort((a, b) => (a.date + a.startTime < b.date + b.startTime ? -1 : 1));

  if (colles.length === 0) {
    const empty = document.createElement('p');
    empty.className = 'empty-state';
    empty.textContent = "Aucune colle à venir — ajoute-en une depuis l'onglet Ajouter.";
    section.appendChild(empty);
  }

  for (const event of colles) {
    const subj = subjectMeta(event.subject, state.settings);
    const chapterTitles = (event.chapterIds || [])
      .map((id) => state.chapters.find((c) => c.id === id)?.title)
      .filter(Boolean);

    const item = document.createElement('div');
    item.className = 'list-item colle-item';
    item.style.borderLeft = `4px solid ${subj.color}`;
    item.innerHTML = `
      <div>
        <div>
          <span class="subject-pill" style="background:${subj.color}">${escapeHtml(subj.label)}</span>
          <strong>${escapeHtml(event.label)}</strong>
        </div>
        <div class="meta">
          ${formatDateFR(event.date)} · ${event.startTime}–${event.endTime} ·
          ${chapterTitles.length ? escapeHtml(chapterTitles.join(', ')) : 'aucun chapitre choisi'}
        </div>
      </div>
    `;

    const actions = document.createElement('div');
    actions.className = 'actions';

    const editBtn = document.createElement('button');
    editBtn.className = 'btn-undo';
    editBtn.textContent = '✎';
    editBtn.title = 'Modifier les chapitres';
    editBtn.addEventListener('click', () => {
      openChapterPicker(section, event, state, onChange);
    });

    const delBtn = document.createElement('button');
    delBtn.textContent = '✕';
    delBtn.title = 'Supprimer cette colle';
    delBtn.addEventListener('click', () => {
      if (confirm(`Supprimer « ${event.label} » ?`)) {
        deleteOneOffEvent(event.id);
        onChange();
      }
    });

    actions.append(editBtn, delBtn);
    item.appendChild(actions);
    section.appendChild(item);
  }

  return section;
}

function openChapterPicker(section, event, state, onChange) {
  const existing = section.querySelector('.chapter-picker');
  if (existing) existing.remove();

  const chapters = state.chapters.filter((c) => c.subject === event.subject && c.status !== 'archive');
  const picker = document.createElement('form');
  picker.className = 'chapter-picker constraint-form';
  picker.innerHTML =
    (chapters.length
      ? '<div class="days-picker">' +
        chapters
          .map(
            (c) =>
              `<label><input type="checkbox" name="chapterId" value="${c.id}" ${
                event.chapterIds?.includes(c.id) ? 'checked' : ''
              } />${escapeHtml(c.title)}</label>`
          )
          .join('') +
        '</div>'
      : '<p class="notice">Aucun chapitre existant pour cette matière.</p>') +
    `
    <label>+ Nouveau chapitre
      <input type="text" name="newChapterTitle" placeholder="ex. Oxydoréduction" />
    </label>
    <button type="submit" class="btn-secondary">Enregistrer les chapitres</button>
  `;

  picker.addEventListener('submit', (e) => {
    e.preventDefault();
    const chapterIds = [...picker.querySelectorAll('input[name="chapterId"]:checked')].map((el) => el.value);
    const newTitle = picker.elements.newChapterTitle.value.trim();
    if (newTitle) {
      const chapter = addChapter({ subject: event.subject, title: newTitle, dateSeen: todayISO(new Date()) });
      chapterIds.push(chapter.id);
    }
    setColleChapters(event.id, chapterIds);
    onChange();
  });

  section.appendChild(picker);
}

