function stageLabel(chapter, settings) {
  const intervals = settings.spacedRepetition.baseIntervalsDays;
  if (chapter.status === 'maitrise') return 'Maîtrisé';
  if (chapter.fusedIntoEventId) return 'Fusionné avec une colle à venir';
  const days = intervals[chapter.stage];
  return days != null ? `J+${days}` : '—';
}

function renderChaptersSection(state) {
  const section = document.createElement('div');
  section.className = 'section';
  section.innerHTML = '<h2>Mes chapitres</h2>';

  const chapters = state.chapters.filter((c) => c.status !== 'archive');
  if (chapters.length === 0) {
    const empty = document.createElement('p');
    empty.className = 'empty-state';
    empty.textContent = "Aucun chapitre pour l'instant.";
    section.appendChild(empty);
    return section;
  }

  const bySubject = new Map();
  for (const c of chapters) {
    if (!bySubject.has(c.subject)) bySubject.set(c.subject, []);
    bySubject.get(c.subject).push(c);
  }

  for (const [subjectId, list] of bySubject) {
    const subj = subjectMeta(subjectId, state.settings);
    const subjHeading = document.createElement('div');
    subjHeading.innerHTML = `<span class="subject-pill" style="background:${subj.color}">${escapeHtml(subj.label)}</span>`;
    subjHeading.style.margin = '4px 0';
    section.appendChild(subjHeading);

    for (const chapter of list.sort((a, b) => (a.nextReviewDate || '') < (b.nextReviewDate || '') ? -1 : 1)) {
      const item = document.createElement('div');
      item.className = 'list-item';
      item.style.borderLeft = `4px solid ${subj.color}`;
      const nextInfo = chapter.status === 'maitrise' || chapter.fusedIntoEventId
        ? stageLabel(chapter, state.settings)
        : `${stageLabel(chapter, state.settings)} · prochaine révision ${chapter.nextReviewDate ? formatDateFR(chapter.nextReviewDate) : '—'}`;
      item.innerHTML = `
        <div>
          <strong>${escapeHtml(chapter.title)}</strong>
          <div class="meta">${nextInfo}</div>
        </div>
      `;
      const archiveBtn = document.createElement('button');
      archiveBtn.textContent = '✕';
      archiveBtn.title = 'Arrêter le suivi de ce chapitre';
      archiveBtn.addEventListener('click', () => {
        if (confirm(`Arrêter la répétition espacée pour « ${chapter.title} » ?`)) {
          archiveChapter(chapter.id);
        }
      });
      item.appendChild(archiveBtn);
      section.appendChild(item);
    }
  }

  return section;
}
