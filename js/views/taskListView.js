// Liste des devoirs, colles à venir (avec édition des chapitres) et mes
// chapitres en répétition espacée. Les tâches auto-générées (préparation de
// colle, révision espacée) ne s'affichent pas dans la liste "devoirs" brute
// — elles se gèrent depuis leurs sections dédiées ci-dessous.

import {
  getState,
  deleteTask,
  deleteOneOffEvent,
  setColleChapters,
  addChapter,
  archiveChapter,
} from '../store.js';
import { TASK_TYPE_LABELS } from '../models.js';
import { formatDateFR, formatDuration, todayISO } from '../utils/date.js';

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str ?? '';
  return div.innerHTML;
}

function subjectMeta(subjectId, settings) {
  return (settings.subjects || []).find((s) => s.id === subjectId) || { label: subjectId, color: '#6B7280' };
}

// Statut affiché, dérivé des sessions plutôt que du champ `task.status`
// (réservé à une fermeture manuelle) : à faire / en cours / terminé.
function computeStatus(task, sessions) {
  const taskSessions = sessions.filter((s) => s.taskId === task.id);
  const doneMinutes = taskSessions.filter((s) => s.status === 'terminee').reduce((sum, s) => sum + s.durationMinutes, 0);
  const remaining = Math.max(0, task.estimatedDurationMinutes - doneMinutes);
  if (task.status === 'termine' || remaining <= 0) return { label: 'Terminé', remaining: 0 };
  if (doneMinutes > 0) return { label: 'En cours', remaining };
  return { label: 'À faire', remaining };
}

// Un devoir "manuel" seulement : les tâches auto-générées se gèrent depuis
// les sections Colles / Chapitres, pas depuis cette liste brute.
function isAutoGenerated(task) {
  return Boolean(task.linkedEventId || task.chapterId);
}

export function renderTaskListView(container) {
  const state = getState();
  const wrapper = document.createElement('div');
  wrapper.className = 'view view-task-list';

  wrapper.appendChild(renderTasksSection(state));
  wrapper.appendChild(renderCollesSection(state, () => rerender(container)));
  wrapper.appendChild(renderChaptersSection(state));

  container.appendChild(wrapper);
}

function rerender(container) {
  container.innerHTML = '';
  renderTaskListView(container);
}

